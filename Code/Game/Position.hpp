#pragma once
using namespace std;

/**
 * @struct Position
 * @brief Represents a coordinate in the game grid.
 *
 * This struct defines the x and y coordinates used
 * to identify a specific location in the grid.
 */
struct Position
{
    /**
     * @brief Horizontal coordinate (x-axis).
     */
    int x;

    /**
     * @brief Vertical coordinate (y-axis).
     */
    int y;
};
